def get_text(key: str, language_code: str = "en") -> str:
    """Return translated UI text; falls back to English then the key itself."""
    lang = (language_code or "en").strip().lower()
    return TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["en"].get(key, key)


